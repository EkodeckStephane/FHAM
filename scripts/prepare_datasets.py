from __future__ import annotations

import argparse
import csv
import hashlib
import os
import tarfile
import urllib.request
import zipfile
from pathlib import Path

from PIL import Image


IMAGE_SUFFIXES = {".pgm", ".png", ".jpg", ".jpeg", ".bmp", ".tif", ".tiff"}
BOSS_DEFAULT = Path(r"C:\Users\User\Downloads\Compressed\cpu_stego_experiments\datasets\BOSSbase")
BOWS2_DEFAULT = Path(r"C:\Users\User\Downloads\Compressed\BOWS2_extracted\cover")
COCO_DEFAULT = Path(r"C:\Users\User\Documents\Articles\DynaCIS-PIR\data\raw\coco\val2017")
BOWS_URL = "http://bows2.ec-lille.fr/BOWS2OrigEp3.tgz"
COCO_URL = "http://images.cocodataset.org/zips/val2017.zip"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def image_files(root: Path) -> list[Path]:
    if not root.exists():
        return []
    return sorted(
        path for path in root.rglob("*")
        if path.is_file() and path.suffix.lower() in IMAGE_SUFFIXES
    )


def download(url: str, archive: Path) -> None:
    archive.parent.mkdir(parents=True, exist_ok=True)
    if archive.exists() and archive.stat().st_size > 0:
        return
    print(f"downloading {url} -> {archive}")
    urllib.request.urlretrieve(url, archive)


def extract(archive: Path, target: Path) -> None:
    target.mkdir(parents=True, exist_ok=True)
    if archive.suffix == ".zip":
        with zipfile.ZipFile(archive) as zf:
            zf.extractall(target)
    elif archive.suffixes[-2:] == [".tar", ".gz"] or archive.suffix == ".tgz":
        with tarfile.open(archive) as tf:
            tf.extractall(target)
    else:
        raise ValueError(f"unsupported archive: {archive}")


def maybe_download_dataset(name: str, root: Path) -> None:
    if image_files(root):
        return
    external = Path("dataset_external")
    try:
        if name == "bows2":
            archive = external / "BOWS2OrigEp3.tgz"
            download(BOWS_URL, archive)
            extract(archive, external / "BOWS2")
        elif name == "coco2017_val":
            archive = external / "val2017.zip"
            download(COCO_URL, archive)
            extract(archive, external / "coco2017")
    except Exception as exc:
        print(f"{name}: download failed: {exc}")


def write_manifest(name: str, root: Path, expected: int, output: Path) -> bool:
    files = image_files(root)
    output.parent.mkdir(parents=True, exist_ok=True)
    rows = []
    for index, path in enumerate(files):
        try:
            with Image.open(path) as image:
                width, height = image.size
                mode = image.mode
        except Exception as exc:
            width, height, mode = 0, 0, f"UNREADABLE:{exc.__class__.__name__}"
        split = "external"
        if name == "bossbase":
            split = "development" if index < 7000 else "validation" if index < 8500 else "test_internal"
        rows.append(
            {
                "dataset": name,
                "split": split,
                "relative_path": path.relative_to(root).as_posix(),
                "sha256": sha256(path),
                "width": width,
                "height": height,
                "mode": mode,
                "source_root": str(root),
                "preprocessing": "manifest only; strict preprocessing cache not generated by this step",
            }
        )
    with output.open("w", newline="", encoding="utf-8") as handle:
        fieldnames = [
            "dataset", "split", "relative_path", "sha256", "width", "height",
            "mode", "source_root", "preprocessing",
        ]
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)
    ok = len(rows) == expected
    print(f"{name}: {len(rows)}/{expected} images -> {output}")
    return ok


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--download-missing", action="store_true")
    parser.add_argument("--strict", action="store_true")
    args = parser.parse_args()

    datasets = {
        "bossbase": (
            Path(os.environ.get("FHAM_BOSSBASE_DIR", str(BOSS_DEFAULT))),
            10000,
        ),
        "bows2": (
            Path(os.environ.get("FHAM_BOWS2_DIR", str(BOWS2_DEFAULT))),
            10000,
        ),
        "coco2017_val": (
            Path(os.environ.get("FHAM_COCO2017_DIR", str(COCO_DEFAULT))),
            5000,
        ),
    }
    all_ok = True
    for name, (root, expected) in datasets.items():
        if args.download_missing:
            maybe_download_dataset(name, root)
        ok = write_manifest(name, root, expected, Path("dataset/manifests") / f"{name}.csv")
        all_ok = all_ok and ok
    return 0 if all_ok or not args.strict else 1


if __name__ == "__main__":
    raise SystemExit(main())
